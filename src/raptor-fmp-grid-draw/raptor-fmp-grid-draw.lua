local GRID_SIZE = 12 -- cells per mapping square: 12 is EFUS size (3 would be nano, wind etc.)
local GRID_SQUARE = 16 -- the smallest build grid on the map is 16x16
local CELL_SIZE = GRID_SIZE * GRID_SQUARE
local MAX_SEGMENT_LENGTH = 24 * GRID_SQUARE
local LINES_PER_BATCH = 10 -- the engine drops map marks sent too fast
local BATCH_INTERVAL = 0.1 -- seconds

-- State
-- ========================================

local lineQueue = {}
local timer = 0

-- Helpers
-- ========================================

local function log(msg)
    Spring.Echo("Raptor Grid Draw: " .. msg)
end

local function hasBit(value, bit)
    return math.floor(value / bit) % 2 == 1
end

-- Queues a line split into segments short enough for a map mark
local function queueLine(x1, z1, x2, z2)
    local dx, dz = x2 - x1, z2 - z1
    local segments = math.ceil(math.sqrt(dx * dx + dz * dz) / MAX_SEGMENT_LENGTH)
    for i = 0, segments - 1 do
        local t1, t2 = i / segments, (i + 1) / segments
        table.insert(lineQueue, { x1 + dx * t1, z1 + dz * t1, x1 + dx * t2, z1 + dz * t2 })
    end
end

-- Marks the cell-long edge along line a at cell offset b
local function addEdge(edges, a, b)
    edges[a] = edges[a] or {}
    edges[a][b] = true
end

-- Queues each run of consecutive edges on lines 0..lineCount as one line, so an
-- edge shared by two cells and a border spanning many cells cost the fewest marks
local function queueRuns(edges, lineCount, cellCount, horizontal)
    for a = 0, lineCount do
        local runStart
        for b = 0, cellCount do -- edges[a][cellCount] is never set, so it ends the last run
            local on = edges[a] and edges[a][b]
            if on and not runStart then
                runStart = b
            elseif not on and runStart then
                if horizontal then
                    queueLine(runStart * CELL_SIZE, a * CELL_SIZE, b * CELL_SIZE, a * CELL_SIZE)
                else
                    queueLine(a * CELL_SIZE, runStart * CELL_SIZE, a * CELL_SIZE, b * CELL_SIZE)
                end
                runStart = nil
            end
        end
    end
end

-- Returns an error message if the mapping doesn't cover the map exactly
local function validateMapping()
    local expectedRows = Game.mapSizeZ / CELL_SIZE
    local expectedCols = Game.mapSizeX / CELL_SIZE
    if #MAPPING ~= expectedRows then
        return "mapping has " .. #MAPPING .. " rows, expected " .. expectedRows
    end
    for row, cells in ipairs(MAPPING) do
        if #cells ~= expectedCols then
            return "row " .. row .. " has " .. #cells .. " columns, expected " .. expectedCols
        end
    end
end

-- Widget callins
-- ========================================

function widget:Initialize()
    local isPvE = BAR.Utilities.Gametype.IsRaptors() or BAR.Utilities.Gametype.IsScavengers()
    if Spring.GetSpectatingState() or not isPvE or Game.mapName ~= "Full Metal Plate 1.7" then
        widgetHandler:RemoveWidget()
        return
    end

    local err = validateMapping()
    if err then
        log("ERROR - " .. err)
        widgetHandler:RemoveWidget()
        return
    end

    -- ponytail: every ally running this widget sends it too, so duplicates are expected
    Spring.SendCommands(
        'say a: Go to Settings -> Interface, turn off "Auto Erase Map Marks" so you never lose the grid lines :)'
    )

    -- hEdges[z][x] runs from cell corner (x, z) to (x + 1, z), vEdges[x][z] to (x, z + 1)
    local hEdges, vEdges = {}, {}
    for row, cells in ipairs(MAPPING) do
        for col, value in ipairs(cells) do
            local x, z = col - 1, row - 1
            if hasBit(value, TOP) then
                addEdge(hEdges, z, x)
            end
            if hasBit(value, BOTTOM) then
                addEdge(hEdges, z + 1, x)
            end
            if hasBit(value, LEFT) then
                addEdge(vEdges, x, z)
            end
            if hasBit(value, RIGHT) then
                addEdge(vEdges, x + 1, z)
            end
            local x1, z1, x2, z2 =
                x * CELL_SIZE, z * CELL_SIZE, (x + 1) * CELL_SIZE, (z + 1) * CELL_SIZE
            if hasBit(value, DIAG_DOWN) then
                queueLine(x1, z1, x2, z2)
            end
            if hasBit(value, DIAG_UP) then
                queueLine(x2, z1, x1, z2)
            end
        end
    end
    queueRuns(hEdges, #MAPPING, #MAPPING[1], true)
    queueRuns(vEdges, #MAPPING[1], #MAPPING, false)
end

-- Draws the queued lines in batches, then removes itself: the marks stay on the map
function widget:Update(dt)
    timer = timer + dt
    if timer < BATCH_INTERVAL then
        return
    end
    timer = 0

    for _ = 1, LINES_PER_BATCH do
        local line = table.remove(lineQueue, 1)
        if not line then
            widgetHandler:RemoveWidget()
            return
        end
        Spring.MarkerAddLine(line[1], 0, line[2], line[3], 0, line[4])
    end
end
